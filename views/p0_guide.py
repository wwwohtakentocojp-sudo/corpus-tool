# --- 読み方 ---------------------------------------------------------------------
st.markdown("## 「読み方」とは")
st.markdown(
    """
頻度・コロケーション・特徴語の画面で表の行を選ぶと、次の4つの見出しで解説が出ます。

- **【この数字が言っていること】** … 数値が示す事実を、統計用語を使わずに
- **【論文に書くなら】** … そのまま貼れる文例（コピーボタン付き）
- **【言ってはいけないこと】** … その数値から言い過ぎになりやすい解釈
- **【次に確認すべきこと】** … 用例を見る、データを増やす、など

後ろの2つは、注意すべき状況のときだけ出ます。出ていなければ、その行には特に落とし穴はありません。
数字の横の **「?」** や、各画面の **「この画面の数字の読み方」** を開くと、指標の意味と注意を確認できます。
"""
)

# --- できないこと ---------------------------------------------------------------
st.markdown("## できないこと・注意")
st.markdown(
    """
- 「なぜそうなるか」は教えません。数字と用例を示し、解釈は研究者が行います。
- PDF は文字情報のあるものだけ読めます。スキャン画像だけの PDF は、OCR ソフトで文字にしてから .txt で読み込んでください。2段組の論文では段が入り混じることがあり、参考文献や脚注も本文と一緒に数えられます。
- 日本語は UniDic の短単位で区切ります。「東京都」は「東京」「都」の2語です（長単位には対応していません）。
- 解説は AI ではなく、決まった判定ルールと文言から組み立てます。同じ数値には必ず同じ注意が出ます。
- 警告の目安（例: 共起 20 回未満で注意）は分野の慣習であって絶対的な基準ではありません。ローカル版では `config.yaml` で変更できます。
"""
)
